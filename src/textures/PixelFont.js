/** Glyph rows for a character (already uppercased), '?' for unknown. */
export function glyphFor(ch) {
  return GLYPHS[ch] ?? GLYPHS['?'];
}

/** Uppercase with Polish locale so ł -> Ł, ó -> Ó etc. */
export function normalizeText(text) {
  return String(text ?? '').toLocaleUpperCase('pl-PL');
}

/** Pixel size [w, h] of a text line rendered at scale 1. */
export function measureText(text) {
  const n = normalizeText(text).length;
  if (!n) return [0, GLYPH_H];
  return [n * GLYPH_W + (n - 1) * LETTER_SPACING, GLYPH_H];
}

/**
 * Render a text line into a bit mask.
 * @returns {{width:number, height:number, data:Uint8Array}} 1 = text pixel
 */
export function renderTextMask(text) {
  const norm = normalizeText(text);
  const [width, height] = measureText(norm);
  const data = new Uint8Array(Math.max(width, 1) * height);
  let ox = 0;
  for (const ch of norm) {
    const rows = glyphFor(ch);
    for (let y = 0; y < GLYPH_H; y++) {
      for (let x = 0; x < GLYPH_W; x++) {
        if (rows[y][x] === '#') data[y * width + ox + x] = 1;
      }
    }
    ox += GLYPH_W + LETTER_SPACING;
  }
  return { width: Math.max(width, 1), height, data };
}
